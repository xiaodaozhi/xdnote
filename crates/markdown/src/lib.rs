unsafe fn workspace_path_buffer(
    document: *const u8,
    document_length: usize,
    target: *const u8,
    target_length: usize,
    make_relative: bool,
) -> RenderBuffer {
    if document_length > 16 * 1024 || target_length > 16 * 1024 {
        return RenderBuffer::error(2);
    }
    if (document.is_null() && document_length != 0) || (target.is_null() && target_length != 0) {
        return RenderBuffer::error(1);
    }
    let result = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: non-null inputs must be live, readable snapshots under the FFI contract.
        let document = if document_length == 0 {
            &[]
        } else {
            unsafe { std::slice::from_raw_parts(document, document_length) }
        };
        let target = if target_length == 0 {
            &[]
        } else {
            unsafe { std::slice::from_raw_parts(target, target_length) }
        };
        let document = std::str::from_utf8(document).map_err(|_| 1u32)?;
        let target = std::str::from_utf8(target).map_err(|_| 1u32)?;
        let bytes = workspace_path_json(document, target, make_relative).map_err(|_| 2u32)?;
        let length = bytes.len();
        let data = Box::into_raw(bytes.into_boxed_slice()) as *mut u8;
        Ok::<_, u32>(RenderBuffer {
            data,
            length,
            status: 0,
        })
    }));
    match result {
        Ok(Ok(buffer)) => buffer,
        Ok(Err(status)) => RenderBuffer::error(status),
        Err(_) => RenderBuffer::error(3),
    }
}

