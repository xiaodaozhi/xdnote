    #[test]
    fn references_follow_markdown_syntax_and_retain_snapshot_ranges() {
        let source = "图片 ![示例](../assets/猫%23.png \"说明\")\n\n[甲][shared] [乙][SHARED]\n\n[shared]: 目录/说明.md \"标题\"\n\n`[伪](fake.md)`\n\n```md\n![伪](fake.png)\n```\n";
        let text = String::from_utf8(references(source).unwrap()).unwrap();
        assert_eq!(text.matches("\"kind\":").count(), 3, "{text}");
        let image = "![示例](../assets/猫%23.png \"说明\")";
        let start = source.find(image).unwrap();
        assert!(
            text.contains(&format!(
                "\"kind\":\"image\",\"start\":{start},\"end\":{}",
                start + image.len()
            )),
            "{text}"
        );
        assert!(
            text.contains("\"target\":\"../assets/猫%23.png\""),
            "{text}"
        );
        assert_eq!(
            text.matches("\"target\":\"目录/说明.md\"").count(),
            2,
            "{text}"
        );
        let definition_start = source.find("[shared]:").unwrap();
        assert_eq!(
            text.matches(&format!("\"definition\":[{definition_start},"))
                .count(),
            2,
            "{text}"
        );
        assert!(!text.contains("fake.md"));
        assert!(!text.contains("fake.png"));
    }

    #[test]
    fn reference_json_is_escaped_and_amplification_is_bounded() {
        let json = String::from_utf8(references("[x](<a\"b> \"t\\\"itle\")").unwrap()).unwrap();
        assert!(json.contains("a\\\"b"), "{json}");
        assert!(json.contains("t\\\"itle"), "{json}");
        assert!(json.contains("\"complete\":true"));
        let source = format!("{}\n\n[r]: {}\n", "[x][r] ".repeat(6000), "a".repeat(4096));
        let partial = String::from_utf8(references(&source).unwrap()).unwrap();
        assert!(partial.contains("\"complete\":false"));
        assert!(partial.contains("reference-expansion-limit"));
        let exactly_at_bound = format!("{}\n\n[r]: {}\n", "[r] ".repeat(99), "a".repeat(1000));
        let boundary = String::from_utf8(references(&exactly_at_bound).unwrap()).unwrap();
        assert!(boundary.contains("\"complete\":false"));
        assert!(matches!(
            references(&"[x](a) ".repeat(100_000)),
            Err(RenderError::OutputLimit)
        ));
        assert!(matches!(
            references(&"x".repeat(MAX_SOURCE_BYTES + 1)),
            Err(RenderError::SourceLimit)
        ));
    }

